static const int rookDirs[4][2] = {{0, 1}, {-1, 0}, {1, 0}, {0, -1}};
static const int bishopDirs[4][2] = {{-1, 1}, {1, 1}, {-1, -1}, {1, -1}};

static uint64_t rayAttacks(int sq, const int dirs[4][2], uint64_t occ) {
	uint64_t bb = 0;
	for (int dir = 0; dir < 4; dir++) {
		int file = sq & 7;
		int rank = sq >> 3;
		for (;;) {
			file += dirs[dir][0];
			rank += dirs[dir][1];

			if (file < 0 || file > 7 || rank < 0 || rank > 7)
				break;

			uint64_t bit = 1ULL << (rank * 8 + file);
			bb |= bit;
			if (occ & bit)
				break;
		}
	}
	return bb;
}

static uint64_t rookMask(int sq) {
	int file = sq & 7;
	int rank = sq >> 3;
	uint64_t mask = 0;
	for (int f = 1; f < 7; f++)
		mask |= 1ULL << (rank * 8 + f);
	for (int r = 1; r < 7; r++)
		mask |= 1ULL << (r * 8 + file);
	return mask & ~(1ULL << sq);
}

static uint64_t bishopMask(int sq) {
	const uint64_t edges = 0xFF818181818181FFULL;
	return rayAttacks(sq, bishopDirs, 0) & ~edges;
}

static void build(MagicEntry *entries, const uint64_t *magics, uint64_t *table,
				  size_t tableSize, int isRook) {
	(void)tableSize;

	int offset = 0;
	for (int sq = 0; sq < 64; sq++) {
		MagicEntry *e = &entries[sq];
		e->mask = isRook ? rookMask(sq) : bishopMask(sq);
		e->magic = magics[sq];
		e->shift = (uint8_t)(64 - __builtin_popcountll(e->mask));
		e->offset = offset;

		uint64_t occ = 0;
		do {
			uint64_t attacks = isRook ? rayAttacks(sq, rookDirs, occ)
									  : rayAttacks(sq, bishopDirs, occ);
			int idx = magicIndex(e, occ);

			assert(table[idx] == 0 || table[idx] == attacks); // bad magic

			// carry rippler trick for iterating
			// over all subsets of a bitboard
			table[idx] = attacks;
			occ = (occ - e->mask) & e->mask;
		} while (occ);

		offset += 1 << (64 - e->shift);
	}
	assert((size_t)offset == tableSize);
}

void initMagics(void) {
	build(rookEntries, rookMagics, rookTable, ROOK_TABLE_SIZE, 1);
	build(bishopEntries, bishopMagics, bishopTable, BISHOP_TABLE_SIZE, 0);
}
